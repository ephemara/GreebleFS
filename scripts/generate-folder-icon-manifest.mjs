import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const iconsDir = path.join(projectRoot, 'public', 'icons');
const outputDir = path.join(projectRoot, 'src', 'config');
const outputFile = path.join(outputDir, 'generatedFolderIconManifest.ts');

const CUSTOM_PREFIX = 'folder_custom_';
const GENERIC_PREFIX = 'folder_generic_';

function stripSvgExtension(fileName) {
  return fileName.replace(/\.svg$/i, '');
}

function stripOpenSuffix(baseName) {
  return baseName.endsWith('_open') ? baseName.slice(0, -5) : baseName;
}

function registerPair(registry, key, fileName, isOpen) {
  const current = registry.get(key) ?? { closed: null, open: null };
  current[isOpen ? 'open' : 'closed'] = fileName;
  registry.set(key, current);
}

function buildManifestSource({ customPairs, genericPairs, defaultPair }) {
  const customEntries = [...customPairs.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([slug, pair]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(pair)},`)
    .join('\n');

  const genericEntries = genericPairs
    .map(pair => `  ${JSON.stringify(pair)},`)
    .join('\n');

  return `/* eslint-disable */
// This file is auto-generated by scripts/generate-folder-icon-manifest.mjs.
// Do not edit by hand.

export type GeneratedFolderIconPair = {
  closed: string;
  open: string | null;
};

export const DEFAULT_FOLDER_ICON = ${JSON.stringify(defaultPair)} as const;

export const CUSTOM_FOLDER_ICONS = {
${customEntries}
} as const satisfies Record<string, GeneratedFolderIconPair>;

export const GENERIC_FOLDER_ICONS = [
${genericEntries}
] as const satisfies readonly GeneratedFolderIconPair[];
`;
}

async function main() {
  const entries = await readdir(iconsDir, { withFileTypes: true });
  const fileNames = entries
    .filter(entry => entry.isFile() && /^folder.*\.svg$/i.test(entry.name))
    .map(entry => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const customPairs = new Map();
  const genericPairs = new Map();
  let defaultClosed = 'folder.svg';
  let defaultOpen = 'folder_open.svg';

  for (const fileName of fileNames) {
    const baseName = stripSvgExtension(fileName);
    const isOpen = baseName.endsWith('_open');
    const baseKey = stripOpenSuffix(baseName);

    if (baseKey === 'folder') {
      if (isOpen) {
        defaultOpen = fileName;
      } else {
        defaultClosed = fileName;
      }
      continue;
    }

    if (baseKey.startsWith(CUSTOM_PREFIX)) {
      registerPair(customPairs, baseKey.slice(CUSTOM_PREFIX.length), fileName, isOpen);
      continue;
    }

    if (baseKey.startsWith(GENERIC_PREFIX)) {
      registerPair(genericPairs, baseKey.slice(GENERIC_PREFIX.length), fileName, isOpen);
    }
  }

  const normalizedCustomPairs = new Map(
    [...customPairs.entries()].map(([slug, pair]) => [slug, {
      closed: pair.closed ?? defaultClosed,
      open: pair.open ?? pair.closed ?? defaultOpen,
    }]),
  );

  const normalizedGenericPairs = [...genericPairs.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([, pair]) => ({
      closed: pair.closed ?? defaultClosed,
      open: pair.open ?? pair.closed ?? defaultOpen,
    }));

  await mkdir(outputDir, { recursive: true });
  await writeFile(
    outputFile,
    buildManifestSource({
      customPairs: normalizedCustomPairs,
      genericPairs: normalizedGenericPairs,
      defaultPair: {
        closed: defaultClosed,
        open: defaultOpen,
      },
    }),
    'utf8',
  );

  console.log(`Generated folder icon manifest with ${normalizedCustomPairs.size} custom pairs and ${normalizedGenericPairs.length} generic pairs.`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
